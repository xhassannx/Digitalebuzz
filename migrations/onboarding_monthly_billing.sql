-- Customer onboarding fee is billed monthly (licensor contract), not on subscription plan events.
-- Schedule is per user: first charge after free_trial_days from signup; pauses while account inactive; resumes after reactivation.

ALTER TABLE users ADD COLUMN IF NOT EXISTS onboarding_next_charge_at TIMESTAMPTZ;
ALTER TABLE users ADD COLUMN IF NOT EXISTS onboarding_monthly_waived BOOLEAN NOT NULL DEFAULT FALSE;

COMMENT ON COLUMN users.onboarding_next_charge_at IS 'When the next monthly licensor onboarding fee row should be created (scheduler)';
COMMENT ON COLUMN users.onboarding_monthly_waived IS 'True if user is in first N included_users and never billed';

-- Allow monthly accrual rows (generated by scheduler)
ALTER TABLE whitelabel_onboarding_fees DROP CONSTRAINT IF EXISTS whitelabel_onboarding_fees_trigger_check;
ALTER TABLE whitelabel_onboarding_fees
  ADD CONSTRAINT whitelabel_onboarding_fees_trigger_check
  CHECK (trigger IN ('assigned', 'purchased', 'renewed', 'upgraded', 'monthly'));

COMMENT ON TABLE whitelabel_onboarding_fees IS 'Customer onboarding monthly fee lines (licensor contract), accrual via scheduler while account active, paid via SaaS owner Orders page';
